#!/bin/sh
# Attach the LSP index and its checksum to an M2Book GitHub release.
#
# Usage: scripts/publish_index.sh TAG [INDEX]
#
# Creates the release TAG when it does not exist yet, otherwise replaces its
# index assets. INDEX defaults to m2-index.jsonl in the repository root.
set -eu

if [ $# -lt 1 ] || [ $# -gt 2 ]; then
    echo "usage: $0 TAG [INDEX]" >&2
    exit 2
fi

tag=$1
repository_root=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
index=${2:-$repository_root/m2-index.jsonl}
index_asset=m2-index.jsonl
checksum_asset=$index_asset.sha256

if [ ! -s "$index" ]; then
    echo "$index is missing or empty; generate it with scripts/generate_reference.sh" >&2
    exit 1
fi
if ! head -n 1 "$index" | grep -q '"kind": *"meta"'; then
    echo "$index does not start with the meta record" >&2
    exit 1
fi

staging=$(mktemp -d)
trap 'rm -rf "$staging"' EXIT
cp "$index" "$staging/$index_asset"
(cd "$staging" && sha256sum "$index_asset" > "$checksum_asset")

notes="LSP index generated by M2Book $tag.

\`$index_asset\` contains documentation and source excerpts from Macaulay2,
copyright The Macaulay2 Authors, distributed under the GNU General Public
License, version 2 or version 3. Individual packages retain their authors'
copyright notices and licenses. \`$checksum_asset\` is its SHA-256 checksum."

if gh release view "$tag" > /dev/null 2>&1; then
    gh release upload "$tag" "$staging/$index_asset" "$staging/$checksum_asset" --clobber
else
    gh release create "$tag" "$staging/$index_asset" "$staging/$checksum_asset" \
        --title "M2Book $tag" --notes "$notes"
fi
